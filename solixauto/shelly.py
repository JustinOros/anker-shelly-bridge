DAY_NAMES = {
    "0": "Sun", "1": "Mon", "2": "Tue", "3": "Wed",
    "4": "Thu", "5": "Fri", "6": "Sat", "7": "Sun",
    "SUN": "Sun", "MON": "Mon", "TUE": "Tue", "WED": "Wed",
    "THU": "Thu", "FRI": "Fri", "SAT": "Sat",
}


def describe_cron(spec):
    parts = str(spec or "").split()
    if len(parts) != 6:
        return str(spec)

    second, minute, hour, day, month, weekday = parts

    if not (second.isdigit() and minute.isdigit() and hour.isdigit()):
        return str(spec)

    clock = f"{int(hour):02d}:{int(minute):02d}"

    if weekday in ("*", "?") and day in ("*", "?"):
        return f"daily at {clock}"

    if weekday not in ("*", "?"):
        names = []
        for token in weekday.replace("-", ",").split(","):
            token = token.strip().upper()
            names.append(DAY_NAMES.get(token, token))

        unique = []
        for name in names:
            if name not in unique:
                unique.append(name)

        if len(unique) == 7:
            return f"daily at {clock}"

        return f"{clock} on {', '.join(unique)}"

    return f"{clock} (day {day}, month {month})"


def describe_job(job):
    timespec = job.get("timespec") or job.get("cron") or ""
    when = describe_cron(timespec)

    actions = []
    for call in job.get("calls") or []:
        method = str(call.get("method") or "")
        params = call.get("params") or {}

        if method.lower() in ("switch.set", "relay.set"):
            state = params.get("on")
            if state is None:
                state = params.get("turn")
            channel = params.get("id", params.get("channel", 0))

            if isinstance(state, str):
                label = state.upper()
            elif state is None:
                label = "toggle"
            else:
                label = "ON" if state else "OFF"

            actions.append(f"turn channel {channel} {label}")
        elif method:
            actions.append(method)

    action_text = ", ".join(actions) if actions else "unknown action"
    enabled = job.get("enable", job.get("enabled", True))
    state = "" if enabled else " [disabled]"
    return f"{when}: {action_text}{state}", bool(enabled)


async def rpc(session, host, method, params=None, auth=None):
    url = f"http://{host}/rpc/{method}"
    try:
        async with session.post(
            url,
            json=params or {},
            timeout=aiohttp.ClientTimeout(total=CONTROL_TIMEOUT),
            auth=auth,
        ) as response:
            if response.status != 200:
                return None
            return await response.json(content_type=None)
    except Exception:
        return None


async def fetch_automation(session, host, gen, config=None, auth=None):
    found = {"schedules": [], "webhooks": [], "timers": {}, "checked": True}

    if gen >= 2:
        schedules = await rpc(session, host, "Schedule.List", auth=auth)
        for job in (schedules or {}).get("jobs") or []:
            text, enabled = describe_job(job)
            found["schedules"].append(
                {"id": job.get("id"), "description": text, "enabled": enabled}
            )

        hooks = await rpc(session, host, "Webhook.List", auth=auth)
        for hook in (hooks or {}).get("hooks") or []:
            found["webhooks"].append(
                {
                    "id": hook.get("id"),
                    "event": hook.get("event", "?"),
                    "name": hook.get("name") or "",
                    "enabled": bool(hook.get("enable", True)),
                }
            )

        for key, entry in (config or {}).items():
            if not key.startswith("switch:"):
                continue
            index = key.split(":", 1)[1]
            timers = {}
            if entry.get("auto_on"):
                timers["auto_on_after"] = entry.get("auto_on_delay")
            if entry.get("auto_off"):
                timers["auto_off_after"] = entry.get("auto_off_delay")
            if entry.get("initial_state") not in (None, "restore_last"):
                timers["initial_state"] = entry.get("initial_state")
            if timers:
                found["timers"][index] = timers
        return found

    relays = (config or {}).get("relays") or []
    for index, relay in enumerate(relays):
        if relay.get("schedule"):
            for rule in relay.get("schedule_rules") or []:
                found["schedules"].append(
                    {"description": f"relay {index}: {rule}", "enabled": True}
                )
        timers = {}
        if relay.get("auto_on"):
            timers["auto_on_after"] = relay.get("auto_on")
        if relay.get("auto_off"):
            timers["auto_off_after"] = relay.get("auto_off")
        if timers:
            found["timers"][str(index)] = timers

    for action, hooks in ((config or {}).get("actions") or {}).get("active", {}).items():
        found["webhooks"].append({"event": action, "name": "", "enabled": True})

    return found


