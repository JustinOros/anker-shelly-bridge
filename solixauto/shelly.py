PROBE_TIMEOUT = 1.5
CONTROL_TIMEOUT = 6.0
SCAN_CONCURRENCY = 64

PROFILE_HEADER = """
Shelly device profile.

Generated by: solixauto discover-shelly
This device is an ACTUATOR. The automation engine turns the listed
channels on and off over local HTTP. No cloud service is involved.

channels:  switch outputs available on this device.
readable:  status fields observed at generation time.
auth:      set username/password here if the device requires it.

If the device gets a new IP, either give it a DHCP reservation or set
host: to its mDNS name and rerun discovery.
"""


def local_addresses():
    found = []

    probe = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        probe.connect(("8.8.8.8", 80))
        found.append(probe.getsockname()[0])
    except OSError:
        pass
    finally:
        probe.close()

    try:
        for info in socket.getaddrinfo(socket.gethostname(), None, socket.AF_INET):
            found.append(info[4][0])
    except socket.gaierror:
        pass

    try:
        import ifaddr

        for adapter in ifaddr.get_adapters():
            for ip in adapter.ips:
                if ip.is_IPv4:
                    found.append(ip.ip)
    except Exception:
        pass

    usable = []
    for address in found:
        try:
            parsed = ipaddress.ip_address(address)
        except ValueError:
            continue
        if parsed.is_loopback or parsed.is_link_local or not parsed.is_private:
            continue
        if address not in usable:
            usable.append(address)

    return usable


def local_subnets():
    networks = []
    for address in local_addresses():
        network = ipaddress.ip_network(f"{address}/24", strict=False)
        if network not in networks:
            networks.append(network)
    return networks


def local_subnet():
    networks = local_subnets()
    return networks[0] if networks else None


def auth_from(profile):
    auth = (profile or {}).get("auth") or {}
    username = auth.get("username")
    password = auth.get("password")
    if username and password:
        return aiohttp.BasicAuth(username, password)
    return None


async def probe_host(session, host, auth=None):
    url = f"http://{host}/shelly"
    try:
        async with session.get(
            url, timeout=aiohttp.ClientTimeout(total=PROBE_TIMEOUT), auth=auth
        ) as response:
            if response.status != 200:
                return None
            payload = await response.json(content_type=None)
    except Exception:
        return None

    if not isinstance(payload, dict):
        return None
    if not ({"mac", "type", "id", "model"} & set(payload)):
        return None

    payload["_host"] = str(host)
    payload["_gen"] = int(payload.get("gen", 1) or 1)
    return payload


async def scan_network(network, verbose=True):
    hosts = list(network.hosts())
    if verbose:
        print(f"Scanning {network} ({len(hosts)} addresses)...")

    found = []
    semaphore = asyncio.Semaphore(SCAN_CONCURRENCY)

    async with aiohttp.ClientSession() as session:

        async def worker(host):
            async with semaphore:
                result = await probe_host(session, host)
                if result:
                    found.append(result)
                    if verbose:
                        print(f"  found {result['_host']} ({describe(result)})")

        await asyncio.gather(*(worker(host) for host in hosts))

    return found


async def probe_hosts(hosts, verbose=True):
    found = []
    async with aiohttp.ClientSession() as session:
        for host in hosts:
            result = await probe_host(session, host)
            if result:
                found.append(result)
                if verbose:
                    print(f"  found {host} ({describe(result)})")
            elif verbose:
                print(f"  no Shelly at {host}")
    return found


def mdns_discover(seconds=5, verbose=True):
    try:
        from zeroconf import ServiceBrowser, Zeroconf
    except ImportError:
        if verbose:
            print("zeroconf not installed, skipping mDNS (pip install zeroconf)")
        return []

    import time

    discovered = []

    class Listener:
        def add_service(self, zeroconf_instance, service_type, name):
            info = zeroconf_instance.get_service_info(service_type, name, timeout=2000)
            if not info:
                return
            for raw in info.parsed_addresses():
                discovered.append(raw)

        def update_service(self, *args):
            pass

        def remove_service(self, *args):
            pass

    zeroconf_instance = Zeroconf()
    listener = Listener()
    browsers = [
        ServiceBrowser(zeroconf_instance, "_shelly._tcp.local.", listener),
        ServiceBrowser(zeroconf_instance, "_http._tcp.local.", listener),
    ]
    if verbose:
        print(f"Listening for mDNS announcements for {seconds}s...")
    time.sleep(seconds)
    for browser in browsers:
        browser.cancel()
    zeroconf_instance.close()

    return sorted(set(discovered))


def describe(payload):
    gen = payload.get("_gen", 1)
    if gen >= 2:
        return f"{payload.get('app') or payload.get('model')} gen{gen}"
    return f"{payload.get('type')} gen1"


