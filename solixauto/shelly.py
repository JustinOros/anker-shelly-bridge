async def clear_auto_timer(session, host, channel, which, gen, auth=None):
    if gen < 2:
        return False
    key = "auto_on" if which == "auto_on_after" else "auto_off"
    result = await rpc(
        session,
        host,
        "Switch.SetConfig",
        {"id": int(channel), "config": {key: False}},
        auth,
    )
    return result is not None


def automation_warnings(automation, channel=None):
    warnings = []
    if not automation:
        return warnings

    for job in automation.get("schedules") or []:
        if job.get("enabled"):
            warnings.append(f"schedule on the device: {job['description']}")

    for index, timers in (automation.get("timers") or {}).items():
        if channel is not None and str(channel) != str(index):
            continue
        for key, value in timers.items():
            if key == "initial_state":
                if str(value).lower() != "off":
                    continue
                warnings.append(
                    f"channel {index} powers up to 'off' instead of restoring its "
                    "last state. After a power cut this plug stays OFF, so anything "
                    "it charges will not recover on its own"
                )
            else:
                warnings.append(
                    f"channel {index} has {key} = {value}s, which will undo "
                    "commands on its own"
                )

    for hook in automation.get("webhooks") or []:
        if hook.get("enabled"):
            label = hook.get("name") or hook.get("event")
            warnings.append(f"webhook/action on the device: {label}")

    return warnings


def extract_channels(payload, status, config=None):
    gen = payload.get("_gen", 1)
    channels = {}

    if gen >= 2:
        for key, value in (status or {}).items():
            if key.startswith("switch:"):
                index = key.split(":", 1)[1]
                channels[index] = {
                    "id": int(index),
                    "name": channel_name_from(config, gen, int(index))
                    or value.get("name")
                    or f"switch {index}",
                    "has_power_meter": "apower" in value,
                }
        if not channels:
            channels["0"] = {"id": 0, "name": "switch 0", "has_power_meter": False}
        return channels

    relays = (status or {}).get("relays") or []
    count = len(relays) or int(payload.get("num_outputs", 1) or 1)
    meters = (status or {}).get("meters") or []
    for index in range(count):
        channels[str(index)] = {
            "id": index,
            "name": channel_name_from(config, gen, index) or f"relay {index}",
            "has_power_meter": index < len(meters),
        }
    return channels


def flatten_status(status, prefix="", out=None, depth=0):
    if out is None:
        out = {}
    if depth > 3:
        return out
    if isinstance(status, dict):
        for key, value in status.items():
            label = f"{prefix}{key}" if not prefix else f"{prefix}.{key}"
            if isinstance(value, (dict, list)):
                flatten_status(value, label, out, depth + 1)
            else:
                out[label] = value
    elif isinstance(status, list):
        for index, value in enumerate(status):
            label = f"{prefix}[{index}]"
            if isinstance(value, (dict, list)):
                flatten_status(value, label, out, depth + 1)
            else:
                out[label] = value
    return out


def find_duplicates(identifier, mac, host, keep):
    import yaml

    duplicates = []
    if not paths.SHELLY_PROFILE_DIR.exists():
        return duplicates

    markers = {str(v).lower() for v in (identifier, mac, host) if v}

    for candidate in sorted(paths.SHELLY_PROFILE_DIR.iterdir()):
        if candidate.suffix not in (".yaml", ".yml") or candidate == keep:
            continue
        try:
            with candidate.open("r", encoding="utf-8") as handle:
                data = yaml.safe_load(handle)
        except Exception:
            continue
        if not isinstance(data, dict):
            continue

        identity = data.get("identity") or {}
        access = data.get("access") or {}
        found = {
            str(identity.get("id") or "").lower(),
            str(identity.get("mac") or "").lower(),
            str(access.get("host") or "").lower(),
        }
        if markers & (found - {""}):
            duplicates.append(candidate)

    return duplicates


def build_profile(payload, status, config=None, automation=None):
    gen = payload.get("_gen", 1)
    host = payload.get("_host")

    if gen >= 2:
        identifier = payload.get("id") or payload.get("mac")
        model = payload.get("model") or payload.get("app") or "unknown"
    else:
        identifier = payload.get("mac")
        model = payload.get("type") or "unknown"

    name = device_name_from(payload, config, gen)

    readable = {}
    for key, value in sorted(flatten_status(status).items()):
        readable[key] = value

    aliases = []
    for candidate in (name, identifier, payload.get("mac"), host):
        if candidate and str(candidate) not in aliases:
            aliases.append(str(candidate))

    return {
        "kind": "shelly",
        "generated": now_iso(),
        "aliases": aliases,
        "identity": {
            "id": identifier,
            "mac": payload.get("mac"),
            "make": "Shelly",
            "model": model,
            "name": name,
            "generation": gen,
            "firmware": payload.get("ver") or payload.get("fw") or "",
        },
        "access": {
            "transport": "local-http",
            "host": host,
            "engine_mode": "read-write",
        },
        "auth": {
            "required": bool(payload.get("auth") or payload.get("auth_en")),
            "username": "",
            "password": "",
        },
        "channels": extract_channels(payload, status, config),
        "device_automation": automation or {},
        "readable": readable,
    }


async def discover(hosts=None, network=None, use_mdns=True, verbose=True):
    paths.ensure_dirs()

    candidates = []

    if hosts:
        candidates.extend(hosts)
    else:
        if use_mdns:
            candidates.extend(mdns_discover(verbose=verbose))

    found = []
    if candidates:
        found.extend(await probe_hosts(sorted(set(candidates)), verbose=verbose))

    if not hosts:
        if network:
            networks = [network]
        else:
            networks = local_subnets()
            if verbose and len(networks) > 1:
                print(
                    f"Detected {len(networks)} local subnet(s): "
                    + ", ".join(str(item) for item in networks)
                )
            if not networks and verbose:
                print(
                    "Could not detect a local subnet. Use --network 192.168.1.0/24 "
                    "or --host <address>."
                )

        for target_network in networks:
            already = {item["_host"] for item in found}
            scanned = await scan_network(target_network, verbose=verbose)
            found.extend(item for item in scanned if item["_host"] not in already)

    written = []
    used_names = {}

    async with aiohttp.ClientSession() as session:
        for payload in found:
            host = payload["_host"]
            gen = payload["_gen"]
            status = await fetch_status(session, host, gen)
            config = await fetch_config(session, host, gen)
            automation = await fetch_automation(session, host, gen, config)
            profile = build_profile(payload, status, config, automation)

            identity = profile["identity"]
            identifier = identity["id"] or identity["mac"] or host
            friendly = identity.get("name") or ""

            if friendly:
                stem = slugify(friendly).lower()
                if stem in used_names:
                    suffix = slugify(str(identifier))[-6:]
                    stem = f"{stem}-{suffix}"
                    print(
                        f"  note: two devices are named {friendly!r}, "
                        f"using {stem}.yaml for this one"
                    )
                used_names[stem] = host
            else:
                stem = f"{slugify(identity['model'])}-{slugify(str(identifier))}".lower()
                print(
                    f"  note: {host} has no friendly name set. Name it in the Shelly "
                    "app and rerun discovery for a readable filename."
                )

            destination = paths.SHELLY_PROFILE_DIR / f"{stem}.yaml"

            stale = find_duplicates(identifier, identity.get("mac"), host, destination)

            save_yaml(destination, profile, header=PROFILE_HEADER)
            written.append(destination)

            for warning in automation_warnings(automation):
                print(f"  CONFLICT RISK: {warning}")

            for other in stale:
                print(
                    f"  WARNING: {other.name} also describes this device. "
                    "Two profiles for one plug will confuse power profiles."
                )
                print(f"           rm {other}")

            if verbose:
                label = f"{friendly} " if friendly else ""
                print(
                    f"  wrote {paths.relative(destination)} "
                    f"{label}({len(profile['channels'])} channel(s))"
                )

    return written


class ShellyTarget:
    def __init__(self, profile_path, channel=None):
        self.profile_path = Path(profile_path)
        self.profile = load_yaml(self.profile_path)
        identity = self.profile.get("identity", {})
        access = self.profile.get("access", {})

        self.host = access.get("host")
        self.generation = int(identity.get("generation", 1) or 1)
        self.model = identity.get("model", "unknown")
        self.label = f"{self.model} @ {self.host}"
        self.auth = auth_from(self.profile)

        channels = self.profile.get("channels") or {}
        if channel is None:
            channel = sorted(channels)[0] if channels else "0"
        self.channel = int(channel)

        if not self.host:
            raise ValueError(f"{self.profile_path} has no access.host")

    async def set_state(self, session, on):
        if self.generation >= 2:
            url = f"http://{self.host}/rpc/Switch.Set"
            payload = {"id": self.channel, "on": bool(on)}
            async with session.post(
                url,
                json=payload,
                timeout=aiohttp.ClientTimeout(total=CONTROL_TIMEOUT),
                auth=self.auth,
            ) as response:
                if response.status != 200:
                    raise RuntimeError(f"HTTP {response.status} from {url}")
                return await response.json(content_type=None)

        turn = "on" if on else "off"
        url = f"http://{self.host}/relay/{self.channel}?turn={turn}"
        async with session.get(
            url, timeout=aiohttp.ClientTimeout(total=CONTROL_TIMEOUT), auth=self.auth
        ) as response:
            if response.status != 200:
                raise RuntimeError(f"HTTP {response.status} from {url}")
            return await response.json(content_type=None)

    async def get_state(self, session):
        status = await fetch_status(session, self.host, self.generation, self.auth)
        if not status:
            return None
        if self.generation >= 2:
            entry = status.get(f"switch:{self.channel}") or {}
            return entry.get("output")
        relays = status.get("relays") or []
        if self.channel < len(relays):
            return relays[self.channel].get("ison")
        return None

    async def automation(self, session):
        config = await fetch_config(session, self.host, self.generation, self.auth)
        return await fetch_automation(
            session, self.host, self.generation, config, self.auth
        )

    async def conflicts(self, session):
        return automation_warnings(await self.automation(session), self.channel)

    async def reachable(self, session):
        try:
            return await self.get_state(session) is not None
        except Exception:
            return False
